
CREATE TABLE POKE_USER (
    ID         VARCHAR2(24)  NOT NULL,
    EMAIL      VARCHAR2(100) NOT NULL,
    PASSWORD   VARCHAR2(255) NOT NULL,
    NAME       VARCHAR2(50)  NOT NULL,
    CREATED_AT TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_POKE_USER PRIMARY KEY (ID),
    CONSTRAINT UK_POKE_USER_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE POKE_SHOPS (
    SHOP_ID           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SHOP_NAME         VARCHAR2(500) NOT NULL,
    SHOP_ADDRESS      VARCHAR2(500),NOT NULL,
    SHOP_AREA         VARCHAR2(500),NOT NULL,
    SHOP_TYPE         VARCHAR2(500),NOT NULL,
    SHOP_OPENTIME     VARCHAR2(500),NOT NULL,
    SHOP_PHONE_NUMBER VARCHAR2(500),
    SHOP_IMG          VARCHAR2(500) NOT NULL
);


CREATE TABLE POKE_NEWS (
    ID          NUMBER(19)      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NEWS_ID     NUMBER(10),
    NEWS_TITLE  VARCHAR2(500),
    NEWS_IMG    VARCHAR2(1000),
    NEWS_URL    VARCHAR2(1000),
    NEWS_TYPE   VARCHAR2(100),
    NEWS_DATE   DATE
);

CREATE TABLE POKE_CODEX (
    POKE_ID     NUMBER(10)   NOT NULL,
    POKE_DESC   VARCHAR2(2000 CHAR),
    POKE_HEIGHT NUMBER(10),
    POKE_IMG    VARCHAR2(1000 CHAR),
    POKE_NAME   VARCHAR2(200 CHAR) NOT NULL,
    POKE_TYPE   VARCHAR2(100 CHAR),
    POKE_WEIGHT NUMBER(10),

    CONSTRAINT PK_POKE_CODEX PRIMARY KEY (POKE_ID)
);

CREATE TABLE POKE_GOODS (
    GOODS_ID       NUMBER(10),
    GOODS_URL      VARCHAR2(500),
    GOODS_TITLE    VARCHAR2(500) NOT NULL,
    GOODS_TYPE     VARCHAR2(50),
    GOODS_DATE     DATE

    CONSTRAINT PK_POKE_GOODS PRIMARY KEY (GOODS_ID)
);

